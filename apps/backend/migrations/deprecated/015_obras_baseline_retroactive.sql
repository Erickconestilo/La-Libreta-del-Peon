-- =====================================================
-- 1. TABLA: obras
-- Proyectos de obra (equivalente a "projects" pero en español)
-- =====================================================

CREATE TABLE IF NOT EXISTS public.obras (
  id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  nombre TEXT NOT NULL,
  ubicacion TEXT,
  tipo TEXT,
  estado TEXT NOT NULL DEFAULT 'activa',
  fecha_inicio DATE,
  notas TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.obras ENABLE ROW LEVEL SECURITY;

CREATE POLICY "obras read"
  ON public.obras
  AS PERMISSIVE
  FOR SELECT
  TO authenticated
  USING (is_active_user());

CREATE POLICY "obras admin insert"
  ON public.obras
  AS PERMISSIVE
  FOR INSERT
  TO authenticated
  WITH CHECK (is_admin());

CREATE POLICY "obras admin update"
  ON public.obras
  AS PERMISSIVE
  FOR UPDATE
  TO authenticated
  USING (is_admin())
  WITH CHECK (is_admin());

CREATE POLICY "obras admin delete"
  ON public.obras
  AS PERMISSIVE
  FOR DELETE
  TO authenticated
  USING (is_admin());

COMMENT ON TABLE public.obras IS 'Proyectos de obra. Convive con "projects" (ADR 001): projects para stations/prisms, obras para campanas/faenas.';
COMMENT ON COLUMN public.obras.estado IS 'Estado de la obra: activa, pausada, cerrada';
COMMENT ON COLUMN public.obras.tipo IS 'Tipo de obra: metro, edificación, túnel, etc.';

-- =====================================================
-- 2. TABLA: campanas
-- Campañas de medición (ciclos de observación por obra)
-- =====================================================

CREATE TABLE IF NOT EXISTS public.campanas (
  id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  obra_id BIGINT NOT NULL REFERENCES public.obras(id) ON DELETE CASCADE,
  nombre TEXT,
  fecha DATE NOT NULL,
  archivo_txt TEXT,
  estado TEXT NOT NULL DEFAULT 'importada',

  -- Resumen estadístico de la campaña
  total_sensores INTEGER NOT NULL DEFAULT 0,
  medidos INTEGER NOT NULL DEFAULT 0,
  no_medidos INTEGER NOT NULL DEFAULT 0,
  nuevos INTEGER NOT NULL DEFAULT 0,
  cobertura_pct DOUBLE PRECISION,

  -- Evaluación de movimientos
  mov_ok INTEGER NOT NULL DEFAULT 0,
  mov_prealerta INTEGER NOT NULL DEFAULT 0,
  mov_alerta INTEGER NOT NULL DEFAULT 0,
  coord_incoherentes INTEGER NOT NULL DEFAULT 0,
  max_asiento_mm DOUBLE PRECISION NOT NULL DEFAULT 0,
  max_levante_mm DOUBLE PRECISION NOT NULL DEFAULT 0,

  -- Metadata de importación
  fichero_origen TEXT,
  operador TEXT,
  descripcion TEXT,
  estacionamiento TEXT, -- Referencia textual al estacionamiento usado

  -- Relación opcional con jornada de trabajo
  jornada_id BIGINT REFERENCES public.jornadas(id) ON DELETE SET NULL,

  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_campanas_obra_id ON public.campanas(obra_id);
CREATE INDEX idx_campanas_fecha ON public.campanas(fecha DESC);
CREATE INDEX idx_campanas_jornada_id ON public.campanas(jornada_id) WHERE jornada_id IS NOT NULL;

ALTER TABLE public.campanas ENABLE ROW LEVEL SECURITY;

CREATE POLICY "campanas read"
  ON public.campanas
  AS PERMISSIVE
  FOR SELECT
  TO authenticated
  USING (is_active_user());

CREATE POLICY "campanas operativo insert"
  ON public.campanas
  AS PERMISSIVE
  FOR INSERT
  TO authenticated
  WITH CHECK (is_operativo());

CREATE POLICY "campanas operativo update"
  ON public.campanas
  AS PERMISSIVE
  FOR UPDATE
  TO authenticated
  USING (is_operativo())
  WITH CHECK (is_operativo());

CREATE POLICY "campanas admin delete"
  ON public.campanas
  AS PERMISSIVE
  FOR DELETE
  TO authenticated
  USING (is_admin());

COMMENT ON TABLE public.campanas IS 'Ciclos de medición por obra. Contiene resumen estadístico (cobertura, movimientos) calculado post-importación.';
COMMENT ON COLUMN public.campanas.estado IS 'Estado de la campaña: importada, validada, cerrada';
COMMENT ON COLUMN public.campanas.cobertura_pct IS 'Porcentaje de sensores medidos sobre total esperado';
COMMENT ON COLUMN public.campanas.mov_ok IS 'Cantidad de sensores con movimiento dentro de límites normales';
COMMENT ON COLUMN public.campanas.mov_prealerta IS 'Cantidad de sensores en rango de prealerta';
COMMENT ON COLUMN public.campanas.mov_alerta IS 'Cantidad de sensores en rango de alerta';

