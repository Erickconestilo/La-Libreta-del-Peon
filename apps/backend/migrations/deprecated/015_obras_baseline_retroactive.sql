-- =====================================================
-- ATENCIÓN: Esta migración es DOCUMENTAL, no se aplica.
-- Las tablas ya existen en Supabase desde antes del control de versiones.
-- Este archivo registra el estado real tal como existe hoy (2026-07-26).
--
-- Contexto:
-- Durante la Fase 0 se descubrió que 6 tablas del modelo "obras" existen
-- en producción con datos reales (72 sensores, 145 mediciones) pero sin
-- archivo de migración correspondiente. Fueron creadas por otra vía
-- (probablemente Codex trabajando directo contra Supabase).
--
-- Decisión (ADR 001, 2026-07-26):
-- Este esquema se adopta como modelo de dominio de faenas para Fases 1-3.
-- La migración 014 (monitoring_rounds) no se aplica para este propósito.
--
-- Datos actuales (verificados con COUNT(*), 2026-07-26):
-- - obras: 6 filas
-- - campanas: 7 filas
-- - jornadas: 0 filas
-- - sensores: 72 filas
-- - mediciones: 145 filas
-- - estacionamientos: 22 filas
--
-- Referencias:
-- - MEMORIA.md §3, §10
-- - FASE_0_INVENTARIO_COMPLETO.md
-- - docs/adr/001-adopt-obras-schema-as-work-domain-model.md
