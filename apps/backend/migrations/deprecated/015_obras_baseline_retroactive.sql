-- =====================================================
-- 4. TABLA: sensores
-- Catálogo de puntos de control por obra
-- =====================================================

CREATE TABLE IF NOT EXISTS public.sensores (
  id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  obra_id BIGINT NOT NULL REFERENCES public.obras(id) ON DELETE CASCADE,
  codigo TEXT NOT NULL,

  -- Coordenadas de referencia
  lat DOUBLE PRECISION,
  lng DOUBLE PRECISION,
  cota_ref DOUBLE PRECISION,

  -- Sistema de coordenadas local/proyectado
  east DOUBLE PRECISION,
  north DOUBLE PRECISION,
  z_local DOUBLE PRECISION,
  coords_calculadas BOOLEAN NOT NULL DEFAULT FALSE,

  -- Clasificación
  itinerario TEXT,
  tipo_sensor TEXT DEFAULT 'nivelacion',
  estado TEXT DEFAULT 'activo',

  -- Metadata
  fecha_instalacion DATE,
  notas TEXT,

  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

  UNIQUE (obra_id, codigo)
);

CREATE INDEX idx_sensores_obra_id ON public.sensores(obra_id);
CREATE INDEX idx_sensores_codigo ON public.sensores(codigo);
CREATE INDEX idx_sensores_tipo ON public.sensores(tipo_sensor);

ALTER TABLE public.sensores ENABLE ROW LEVEL SECURITY;

CREATE POLICY "sensores read"
  ON public.sensores
  AS PERMISSIVE
  FOR SELECT
  TO authenticated
  USING (is_active_user());

CREATE POLICY "sensores admin insert"
  ON public.sensores
  AS PERMISSIVE
  FOR INSERT
  TO authenticated
  WITH CHECK (is_admin());

CREATE POLICY "sensores admin update"
  ON public.sensores
  AS PERMISSIVE
  FOR UPDATE
  TO authenticated
  USING (is_admin())
  WITH CHECK (is_admin());

CREATE POLICY "sensores admin delete"
  ON public.sensores
  AS PERMISSIVE
  FOR DELETE
  TO authenticated
  USING (is_admin());

COMMENT ON TABLE public.sensores IS 'Catálogo de puntos de control (sensores, prismas, referencias) por obra. Equivalente a "control_points" de migración 014 (descartada).';
COMMENT ON COLUMN public.sensores.codigo IS 'Código único del sensor dentro de la obra (ej: CN3, PT-01)';
COMMENT ON COLUMN public.sensores.tipo_sensor IS 'Tipo de sensor: nivelacion, prisma, inclinometro, piezometro, etc.';
COMMENT ON COLUMN public.sensores.coords_calculadas IS 'TRUE si east/north/z_local fueron calculadas (no importadas directamente)';

-- =====================================================
-- 5. TABLA: mediciones
-- Observaciones individuales por campaña y sensor
-- =====================================================

CREATE TABLE IF NOT EXISTS public.mediciones (
  id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  obra_id BIGINT NOT NULL REFERENCES public.obras(id) ON DELETE CASCADE,
  campana_id BIGINT NOT NULL REFERENCES public.campanas(id) ON DELETE CASCADE,
  estacionamiento_id BIGINT REFERENCES public.estacionamientos(id) ON DELETE SET NULL,
  sensor_id BIGINT REFERENCES public.sensores(id) ON DELETE SET NULL,

  -- Identificación del punto medido
  point_id_csv TEXT NOT NULL, -- Código del punto tal como viene en el archivo importado
  fecha_medicion TEXT NOT NULL,

  -- Valores observados
  elev_medida DOUBLE PRECISION NOT NULL,
  east_csv DOUBLE PRECISION,
  north_csv DOUBLE PRECISION,

  -- Metadata de medición
  instrumento TEXT,
  comentario TEXT,

  -- Cálculos y validaciones
  desnivel DOUBLE PRECISION,
  movimiento TEXT NOT NULL DEFAULT 'ok', -- ok, prealerta, alerta
  estado_match TEXT NOT NULL, -- exact, fuzzy, new, unmatched
  tipo_punto TEXT NOT NULL DEFAULT 'sensor', -- sensor, referencia, control
  coordenadas_ok BOOLEAN NOT NULL DEFAULT TRUE,
  dist_xy_m DOUBLE PRECISION,
  posible_typo BOOLEAN NOT NULL DEFAULT FALSE,
  similar_a TEXT,

  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_mediciones_obra_id ON public.mediciones(obra_id);
CREATE INDEX idx_mediciones_campana_id ON public.mediciones(campana_id);
CREATE INDEX idx_mediciones_sensor_id ON public.mediciones(sensor_id) WHERE sensor_id IS NOT NULL;
CREATE INDEX idx_mediciones_point_id ON public.mediciones(point_id_csv);
CREATE INDEX idx_mediciones_movimiento ON public.mediciones(movimiento) WHERE movimiento != 'ok';

ALTER TABLE public.mediciones ENABLE ROW LEVEL SECURITY;

CREATE POLICY "mediciones read"
  ON public.mediciones
  AS PERMISSIVE
  FOR SELECT
  TO authenticated
  USING (is_active_user());

CREATE POLICY "mediciones admin insert"
  ON public.mediciones
  AS PERMISSIVE
  FOR INSERT
  TO authenticated
  WITH CHECK (is_admin());

CREATE POLICY "mediciones admin update"
  ON public.mediciones
  AS PERMISSIVE
  FOR UPDATE
  TO authenticated
  USING (is_admin())
  WITH CHECK (is_admin());

CREATE POLICY "mediciones admin delete"
  ON public.mediciones
  AS PERMISSIVE
  FOR DELETE
  TO authenticated
  USING (is_admin());

COMMENT ON TABLE public.mediciones IS 'Observaciones individuales por campaña. Incluye validación integrada (matching, coordenadas, movimiento). Equivalente a "instrument_readings" de migración 014 (descartada) pero con validación propia.';
COMMENT ON COLUMN public.mediciones.estado_match IS 'Resultado del matching point_id_csv vs. sensores.codigo: exact (encontrado tal cual), fuzzy (encontrado con normalización), new (sensor nuevo), unmatched (no encontrado)';
COMMENT ON COLUMN public.mediciones.movimiento IS 'Evaluación de movimiento respecto a campaña anterior: ok (dentro de límites), prealerta, alerta';
COMMENT ON COLUMN public.mediciones.posible_typo IS 'TRUE si el point_id_csv es similar a otro código existente pero no idéntico (ej: CN3 vs CN-3)';

